import { readFile, readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";

// Collect production packages only, including installed peers. Preserve each
// publisher's complete notice; no network access or guessed license text.
const root = resolve(process.cwd());
const packages = new Map();
const missing = [];
async function visit(name, parent) {
  const require = createRequire(join(parent, "package.json"));
  let directory;
  try {
    directory = dirname(require.resolve(`${name}/package.json`));
  } catch {
    directory = dirname(require.resolve(name));
    while (true) {
      try {
        const value = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
        if (value.name === name) break;
      } catch { /* Search enclosing package, not the entry's nested dist folder. */ }
      const next = dirname(directory);
      if (next === directory) throw new Error(`Cannot locate ${name} metadata`);
      directory = next;
    }
  }
  const metadata = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
  const identity = `${metadata.name}@${metadata.version}`;
  if (packages.has(identity)) return;
  const files = (await readdir(directory)).filter((file) => /^(licen[sc]e|copying|notice)([.-]|$)/i.test(file));
  const supplemental = join(root, "licenses/web-upstream", `${metadata.name.replaceAll("/", "_")}-${metadata.version}.txt`);
  const notices = files.length ? await Promise.all(files.sort().map((file) => readFile(join(directory, file), "utf8"))) : [await readFile(supplemental, "utf8").catch(() => { missing.push(identity); return ""; })];
  packages.set(identity, `${identity} (${metadata.license || "see notice"})\n${notices.join("\n").replace(/\r\n?/g, "\n").trim()}`);
  for (const dependency of Object.keys({ ...metadata.dependencies, ...metadata.peerDependencies }).sort()) {
    if (metadata.peerDependenciesMeta?.[dependency]?.optional) continue;
    await visit(dependency, directory);
  }
}
const manifest = JSON.parse(await readFile(join(root, "web/package.json"), "utf8"));
for (const name of Object.keys(manifest.dependencies).sort()) await visit(name, join(root, "web"));
if (missing.length) throw new Error(`Missing notices: ${missing.join(", ")}`);
const output = "KONE Web — third-party production dependency notices\nGenerated by scripts/tasks/web-notices.mjs from the locked installed packages.\n\n" + [...packages].sort(([a], [b]) => a.localeCompare(b, "en")).map(([, notice]) => notice).join("\n\n--------------------\n\n") + "\n";
const target = join(root, "licenses/web-third-party.txt");
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== output) throw new Error("Web notices are stale; run just ci web-build");
} else await writeFile(target, output);
console.log(`Web dependency notices: ${packages.size} packages`);
